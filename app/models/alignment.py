"""
GeneWeaver alignment database models.

Stores alignment job metadata and the genomic alignment results
generated by the GeneWeaver compute engine.
"""

from __future__ import annotations

import uuid
from typing import Any

from sqlalchemy import (
    JSON,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Uuid,
    func,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.database import Base


class AlignmentJob(Base):
    """A submitted alignment job and its reproducibility metadata."""

    __tablename__ = "alignment_jobs"

    __table_args__ = (
        CheckConstraint(
            "status IN ('pending', 'running', 'completed', 'failed', 'cancelled')",
            name="ck_alignment_jobs_status",
        ),
        CheckConstraint(
            "progress >= 0 AND progress <= 100",
            name="ck_alignment_jobs_progress",
        ),
        Index(
            "ix_alignment_jobs_status_created_at",
            "status",
            "created_at",
        ),
        Index(
            "ix_alignment_jobs_reference_genome",
            "reference_genome",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # Submitted biological input.
    guide_sequence: Mapped[str] = mapped_column(
        String(256),
        nullable=False,
    )

    pam_type: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default="NGG",
        server_default=text("'NGG'"),
    )

    # Reference genome identity and provenance.
    reference_genome: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
    )

    reference_dataset_version: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
    )

    reference_dataset_checksum: Mapped[str | None] = mapped_column(
        String(128),
        nullable=True,
    )

    # Algorithm and execution provenance.
    algorithm_name: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
    )

    algorithm_version: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
    )

    compute_backend: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default="cpu",
        server_default=text("'cpu'"),
    )

    parameters: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    # Job lifecycle.
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="pending",
        server_default=text("'pending'"),
    )

    progress: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default=text("0"),
    )

    error_message: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    created_at: Mapped[Any] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    started_at: Mapped[Any | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    completed_at: Mapped[Any | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    updated_at: Mapped[Any] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    # One job can produce multiple alignment results.
    results: Mapped[list[AlignmentResult]] = relationship(
        back_populates="job",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    def __repr__(self) -> str:
        """Return a concise representation for debugging."""
        return (
            f"AlignmentJob(id={self.id!r}, "
            f"status={self.status!r}, "
            f"reference_genome={self.reference_genome!r})"
        )


class AlignmentResult(Base):
    """A genomic alignment result associated with an alignment job."""

    __tablename__ = "alignment_results"

    __table_args__ = (
        CheckConstraint(
            "start_position >= 0",
            name="ck_alignment_results_start_position",
        ),
        CheckConstraint(
            "end_position > start_position",
            name="ck_alignment_results_coordinate_range",
        ),
        CheckConstraint(
            "strand IN ('+', '-')",
            name="ck_alignment_results_strand",
        ),
        CheckConstraint(
            "mismatch_count >= 0",
            name="ck_alignment_results_mismatch_count",
        ),
        Index(
            "ix_alignment_results_job_id",
            "job_id",
        ),
        Index(
            "ix_alignment_results_chromosome_position",
            "chromosome",
            "start_position",
        ),
        Index(
            "ix_alignment_results_mismatch_count",
            "mismatch_count",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    job_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("alignment_jobs.id", ondelete="CASCADE"),
        nullable=False,
    )

    # Genomic location.
    chromosome: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
    )

    # Coordinates use a zero-based, half-open interval:
    # start_position is included; end_position is excluded.
    start_position: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    end_position: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    strand: Mapped[str] = mapped_column(
        String(1),
        nullable=False,
    )

    # Matched sequence and PAM information.
    target_sequence: Mapped[str] = mapped_column(
        String(256),
        nullable=False,
    )

    pam_sequence: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
    )

    # Off-target mismatch information.
    mismatch_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    mismatch_positions: Mapped[list[int]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )

    # Algorithm-specific screening score.
    # This is not a clinical probability.
    score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    score_components: Mapped[dict[str, Any] | None] = mapped_column(
        JSON,
        nullable=True,
    )

    result_metadata: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    created_at: Mapped[Any] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    job: Mapped[AlignmentJob] = relationship(
        back_populates="results",
    )

    def __repr__(self) -> str:
        """Return a concise representation for debugging."""
        return (
            f"AlignmentResult(id={self.id!r}, "
            f"chromosome={self.chromosome!r}, "
            f"start_position={self.start_position!r}, "
            f"mismatch_count={self.mismatch_count!r})"
        )
